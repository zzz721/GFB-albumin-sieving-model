def write_radius_outputs(
    results: pd.DataFrame,
    out_dir: Path,
    base_radius: float,
    radii: list[float],
    *,
    bootstrap_repeats: int = DEFAULT_BOOTSTRAP_REPEATS,
    bootstrap_sample_size: int = DEFAULT_BOOTSTRAP_SAMPLE_SIZE,
    bootstrap_seed: int = DEFAULT_BOOTSTRAP_SEED,
) -> pd.DataFrame:
    results.to_csv(out_dir / "per_sample_radius_results.csv", index=False, encoding="utf-8-sig")
    write_radius_input_dirs(results, out_dir)

    summary = build_summary(results)
    summary.to_csv(out_dir / "radius_series_summary.csv", index=False, encoding="utf-8-sig")
    bootstrap_summary = build_radius_bootstrap_summary(
        results,
        out_dir,
        repeats=int(bootstrap_repeats),
        sample_size=int(bootstrap_sample_size),
        seed=int(bootstrap_seed),
    )
    q_alb_col = "Q_alb_total_times_C0" if "Q_alb_total_times_C0" in results.columns else "J_s_total_times_C0"
    pivot = results.pivot_table(
        index=["sample_id", "sample_name", "sample_type", "run_index", "thickness_nm"],
        columns="radius_code",
        values=["sieving_coefficient", "Q_total_m3s", q_alb_col, "status"],
        aggfunc="first",
    )
    pivot.columns = ["_".join(str(x) for x in col if x) for col in pivot.columns.to_flat_index()]
    pivot.reset_index().to_csv(out_dir / "paired_sieving_radius_series.csv", index=False, encoding="utf-8-sig")

    base_label = _radius_label(base_radius)
    plot_integrated_radius_response(summary, out_dir, bootstrap_summary=bootstrap_summary)
    plot_integrated_radius_4p25_bootstrap_bar(summary, out_dir, bootstrap_summary=bootstrap_summary)

    sample_types_present = sorted(results["sample_type"].dropna().astype(str).str.upper().unique())
    for st in sample_types_present:
        plot_paired_radius_scatter(results, summary, out_dir, base_label, sample_type=st, stem_suffix=st)
        plot_thickness_scatter(
            results,
            summary,
            out_dir,
            stem=f"thickness_vs_sieving_radius_series_{st}",
            title="sieving across solute radii",
            sample_type=st,
        )
    plot_combined_solute_radius_sensitivity(results, summary, out_dir, base_label, bootstrap_summary=bootstrap_summary)
    return summary


def main() -> None:
    args = build_parser().parse_args()
    run_result_dir = _resolve_cli_path(args.run_result_dir)
    networks_dir = _resolve_cli_path(args.networks_dir) if args.networks_dir else run_result_dir / "phase3_synthetic" / "networks"
    baseline_phase4_dir = _resolve_cli_path(args.baseline_phase4_dir) if args.baseline_phase4_dir else run_result_dir / "phase4_sieving"
    out_dir = _resolve_cli_path(args.output_dir) if args.output_dir else run_result_dir / "solute_radius_sensitivity"
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.radii_nm:
        radii = [float(v) for v in args.radii_nm]
    elif args.new_radii_nm:
        radii = [float(args.base_solute_radius_nm), *[float(v) for v in args.new_radii_nm]]
    else:
        base = float(args.base_solute_radius_nm)
        radii = [base, *[base + float(delta) for delta in args.extra_radius_deltas_nm]]
    if len(radii) < 2:
        raise SystemExit("At least two radii are required.")

    if args.plot_only:
        existing_csv = out_dir / "per_sample_radius_results.csv"
        if not existing_csv.is_file():
            raise SystemExit(f"--plot-only requires existing CSV: {existing_csv}")
        results = pd.read_csv(existing_csv)
        for col in [
            "solute_radius_nm",
            "run_index",
            "thickness_nm",
            "sieving_coefficient",
            "Q_total_m3s",
            "Q_alb_total_times_C0",
            "J_s_total_times_C0",
            "C0",
        ]:
            if col in results.columns:
                results[col] = pd.to_numeric(results[col], errors="coerce")
        if "radius_code" not in results.columns and "solute_radius_nm" in results.columns:
            results["radius_code"] = results["solute_radius_nm"].map(_radius_code)
        if "radius_label" not in results.columns and "solute_radius_nm" in results.columns:
            results["radius_label"] = results["solute_radius_nm"].map(_radius_label)
        discovered_radii = (
            pd.to_numeric(results.get("solute_radius_nm"), errors="coerce")
            .dropna()
            .drop_duplicates()
            .sort_values()
            .tolist()
        )
        if len(discovered_radii) >= 2:
            radii = [float(x) for x in discovered_radii]
            base_radius = radii[0]
        else:
            base_radius = radii[0]
        summary = write_radius_outputs(
            results,
            out_dir,
            base_radius,
            radii,
            bootstrap_repeats=int(args.bootstrap_repeats),
            bootstrap_sample_size=int(args.bootstrap_sample_size),
            bootstrap_seed=int(args.bootstrap_seed),
        )
        print(summary.to_string(index=False))
        print(f"Redrew figures from existing CSV: {existing_csv}")
        print(f"Saved to: {out_dir}")
        return

    sample_types_arg = str(args.sample_types).strip()
    sample_types = None if sample_types_arg.lower() == "all" else {x.strip().upper() for x in sample_types_arg.split(",") if x.strip()}
    samples = discover_networks(networks_dir, run_result_dir, sample_types, args.max_samples_per_type)
    if samples.empty:
        raise SystemExit(f"No network pairs found in {networks_dir}")

    sample_counts = samples.groupby("sample_type").size().to_dict()
    print(f"Discovered {len(samples)} network pairs: {sample_counts}")
    print(f"Radii: {', '.join(_radius_label(r) for r in radii)}")
    print(f"Output: {out_dir}")
    if args.dry_run:
        print("Dry run only; no Phase4 calls made.")
        samples.to_csv(out_dir / "dry_run_discovered_networks.csv", index=False, encoding="utf-8-sig")
        return

    all_rows: list[dict[str, Any]] = []
    base_radius = radii[0]
    if args.rerun_baseline:
        phase4_dir = out_dir / f"phase4_radius_{_radius_code(base_radius)}"
        rows = run_radius_results(
            samples,
            networks_dir=networks_dir,
            phase4_dir=phase4_dir,
            logs_dir=out_dir / "logs" / _radius_code(base_radius),
            radius_nm=base_radius,
            hydrodynamic_radius_nm=float(args.hydrodynamic_radius_nm),
            jobs=max(1, int(args.jobs)),
            force=bool(args.force),
            keep_logs=bool(args.keep_logs),
            keep_phase4_diagnostics=bool(args.keep_phase4_diagnostics),
            zero_threshold=float(args.zero_threshold),
            invalid_max_sieving=float(args.invalid_max_sieving),
        )
    else:
        rows = load_baseline_results(
            samples,
            baseline_phase4_dir,
            base_radius_nm=base_radius,
            hydrodynamic_radius_nm=float(args.hydrodynamic_radius_nm),
            zero_threshold=float(args.zero_threshold),
            invalid_max_sieving=float(args.invalid_max_sieving),
        )
    all_rows.extend(rows)

    for radius in radii[1:]:
        phase4_dir = out_dir / f"phase4_radius_{_radius_code(radius)}"
        print(f"Running/reusing Phase4 for radius {_radius_label(radius)} -> {phase4_dir}")
        rows = run_radius_results(
            samples,
            networks_dir=networks_dir,
            phase4_dir=phase4_dir,
            logs_dir=out_dir / "logs" / _radius_code(radius),
            radius_nm=radius,
            hydrodynamic_radius_nm=float(args.hydrodynamic_radius_nm),
            jobs=max(1, int(args.jobs)),
            force=bool(args.force),
            keep_logs=bool(args.keep_logs),
            keep_phase4_diagnostics=bool(args.keep_phase4_diagnostics),
            zero_threshold=float(args.zero_threshold),
            invalid_max_sieving=float(args.invalid_max_sieving),
        )
        all_rows.extend(rows)

    results = pd.DataFrame(all_rows)
    summary = write_radius_outputs(
        results,
        out_dir,
        base_radius,
        radii,
        bootstrap_repeats=int(args.bootstrap_repeats),
        bootstrap_sample_size=int(args.bootstrap_sample_size),
        bootstrap_seed=int(args.bootstrap_seed),
    )

    print(summary.to_string(index=False))
    print(f"Saved to: {out_dir}")


if __name__ == "__main__":
    main()
