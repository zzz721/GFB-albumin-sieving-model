def _radius_sort_key(label: Any) -> float:
    text = str(label)
    match = re.search(r"[-+]?\d*\.?\d+", text)
    if match:
        return _safe_float(match.group(0), math.inf)
    return math.inf


def _radius_series_color(sample_type: Any, radius_label: Any, *, zero: bool = False) -> str:
    sample_type = str(sample_type).upper()
    radius_label = str(radius_label)
    palette = RADIUS_SERIES_ZERO_COLORS if zero else RADIUS_SERIES_COLORS
    if sample_type in palette and radius_label in palette[sample_type]:
        return palette[sample_type][radius_label]
    if zero and radius_label in ZERO_COLORS:
        return ZERO_COLORS[radius_label]
    if radius_label in RADIUS_COLORS:
        return RADIUS_COLORS[radius_label]
    return SAMPLE_TYPE_COLORS.get(sample_type, "#777777")


def _sample_type_label(sample_type: Any) -> str:
    return SAMPLE_TYPE_LABELS.get(str(sample_type).upper(), str(sample_type))


def _electrostatic_radius_legend_label(radius_label: Any) -> str:
    text = str(radius_label)
    if text == "3.55 nm":
        return "Without electrostatic exclusion"
    if text == "4.25 nm":
        return "With electrostatic exclusion"
    return f"Radius {text}"


