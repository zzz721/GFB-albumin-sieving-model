def _bootstrap_sd_lookup(bootstrap_summary: pd.DataFrame | None) -> dict[tuple[str, str], float]:
    if bootstrap_summary is None or len(bootstrap_summary) == 0:
        return {}
    out: dict[tuple[str, str], float] = {}
    for _, row in bootstrap_summary.iterrows():
        key = (str(row.get("radius_label")), str(row.get("sample_type")).upper())
        sd = _safe_float(row.get("bootstrap_sd"), math.nan)
        if math.isfinite(sd):
            out[key] = sd
    return out


