def _draw_paired_radius_panel(
    ax,
    df: pd.DataFrame,
    summary: pd.DataFrame,
    base_label: str,
    sample_type: str,
) -> None:
    st = str(sample_type).upper()
    plot_df = df[df["sample_type"].astype(str).str.upper().eq(st)].copy()
    pivot = plot_df.pivot_table(
        index=["sample_id", "sample_type", "run_index", "thickness_nm"],
        columns="radius_label",
        values="sieving_coefficient",
        aggfunc="first",
    ).reset_index()
    labels = sorted([c for c in plot_df["radius_label"].drop_duplicates().tolist() if c != base_label], key=_radius_sort_key)
    if base_label not in pivot.columns or not labels:
        ax.set_axis_off()
        return
    x0 = pd.to_numeric(pivot[base_label], errors="coerce").to_numpy(float)
    for label in labels:
        y = pd.to_numeric(pivot[label], errors="coerce").to_numpy(float)
        valid = np.isfinite(x0) & np.isfinite(y) & (x0 >= 0.0) & (x0 <= 1.0) & (y >= 0.0) & (y <= 1.0)
        ax.scatter(
            _map_paired_compact_zero(x0[valid]),
            _map_paired_compact_zero(y[valid]),
            s=28,
            marker=SAMPLE_TYPE_MARKERS.get(st, "o"),
            color=SAMPLE_TYPE_COLORS.get(st, "#777777"),
            alpha=0.62,
            edgecolors="white",
            linewidths=0.28,
            label=f"{label} (n={int(valid.sum())})",
        )
    _, _, bottom = _paired_compact_axis_coords()
    ax.plot([bottom, 0.0], [bottom, 0.0], color="#30363b", ls="--", lw=1.0, alpha=0.72)
    _format_paired_compact_zero_axes(ax)
    ax.set_xlabel(f"{base_label}", fontsize=12.2)
    y_label = str(labels[0]) if len(labels) == 1 else "Increased radius"
    ax.set_ylabel(y_label, fontsize=12.2)
    ax.set_title(f"{_sample_type_label(st)} paired sieving comparison", fontsize=14.0, pad=11)
    _polish(ax)
    ax.legend(frameon=False, loc="upper left", fontsize=10.0)


def _draw_thickness_radius_panel(
    ax,
    df: pd.DataFrame,
    summary: pd.DataFrame,
    sample_type: str,
) -> None:
    st = str(sample_type).upper()
    plot_df = df[df["sample_type"].astype(str).str.upper().eq(st)].copy()
    rng = np.random.default_rng(20260615)
    labels_sorted = sorted(plot_df["radius_label"].drop_duplicates().tolist(), key=_radius_sort_key)
    for label in labels_sorted:
        sub = plot_df[plot_df["radius_label"].eq(label)]
        sc = pd.to_numeric(sub["sieving_coefficient"], errors="coerce")
        th = pd.to_numeric(sub["thickness_nm"], errors="coerce")
        valid = th.notna() & _valid_sieving_mask(sub)
        if not valid.any():
            continue
        jitter = rng.normal(0.0, 0.35, size=int(valid.sum()))
        x = th[valid].to_numpy(float) + jitter
        y = sc[valid].to_numpy(float)
        y_plot = _map_thickness_compact_y(y)
        pos = y >= THICKNESS_SIEVING_LOG_FLOOR
        ax.scatter(
            x[~pos],
            y_plot[~pos],
            s=20,
            marker=SAMPLE_TYPE_MARKERS.get(st, "o"),
            color=_radius_series_color(st, label),
            alpha=0.38,
            linewidths=0,
            zorder=2,
        )
        ax.scatter(
            x[pos],
            y_plot[pos],
            s=26,
            marker=SAMPLE_TYPE_MARKERS.get(st, "o"),
            color=_radius_series_color(st, label),
            alpha=0.62,
            edgecolors="white",
            linewidths=0.25,
            zorder=3,
            label=_electrostatic_radius_legend_label(label),
        )
    _, zero_coord, _ = _thickness_compact_y_coords()
    ax.axhline(zero_coord, color="#9aa3ab", lw=0.8, alpha=0.55, zorder=0)
    th_all = pd.to_numeric(plot_df["thickness_nm"], errors="coerce")
    finite_th = th_all[np.isfinite(th_all)]
    if st == "WT":
        ax.set_xlim(40.0, 180.0)
    else:
        xmax = max(190.0, float(finite_th.max()) * 1.04) if len(finite_th) else 190.0
        ax.set_xlim(0.0, xmax)
    _format_thickness_compact_y_axis(ax)
    ax.set_xlabel("Thickness (nm)", fontsize=12.5)
    ax.set_ylabel("Sieving coefficient", fontsize=12.5)
    ax.set_title(f"{_sample_type_label(st)} thickness-sieving distribution", fontsize=14.0, pad=11)
    _polish(ax)
    handles, legend_labels = ax.get_legend_handles_labels()
    if handles:
        ax.legend(
            handles,
            legend_labels,
            frameon=False,
            loc="upper right",
            fontsize=10.0,
            ncol=max(1, len(labels_sorted)),
        )


