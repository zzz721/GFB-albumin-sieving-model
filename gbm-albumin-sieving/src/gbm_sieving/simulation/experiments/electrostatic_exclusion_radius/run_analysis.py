def _floor_value(df: pd.DataFrame) -> float:
    sc = pd.to_numeric(df["sieving_coefficient"], errors="coerce")
    vals = sc[np.isfinite(sc) & (sc > 0)].to_numpy(float)
    if len(vals) == 0:
        return 1e-9
    return float(10 ** (np.floor(np.log10(np.min(vals))) - 0.25))


def _map_zero(values: np.ndarray, floor: float) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    return np.where(np.isfinite(values) & (values > 0), values, floor)


def _format_log_ticks(ax, floor: float, axis: str) -> None:
    ticks = [floor, 1e-8, 1e-6, 1e-4, 1e-3, 1e-2, 1e-1, 1.0]
    lo, hi = ax.get_xlim() if axis == "x" else ax.get_ylim()
    ticks = [t for t in ticks if lo <= t <= hi and (t == floor or t / max(floor, 1e-300) >= 3.5)]
    labels = ["0" if abs(t - floor) / max(floor, 1e-300) < 1e-9 else f"$10^{{{int(np.log10(t))}}}$" for t in ticks]
    if axis == "x":
        ax.set_xticks(ticks)
        ax.set_xticklabels(labels)
    else:
        ax.set_yticks(ticks)
        ax.set_yticklabels(labels)


