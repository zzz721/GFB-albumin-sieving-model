def _paired_compact_axis_coords() -> tuple[float, float, float]:
    log_floor = float(np.log10(PAIRED_RADIUS_LOG_FLOOR))
    zero_coord = log_floor - PAIRED_RADIUS_ZERO_GAP
    bottom = zero_coord - PAIRED_RADIUS_ZERO_PAD
    return log_floor, zero_coord, bottom


def _map_paired_compact_zero(values: np.ndarray) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    log_floor, zero_coord, _ = _paired_compact_axis_coords()
    out = np.full(values.shape, zero_coord, dtype=float)
    pos = np.isfinite(values) & (values >= PAIRED_RADIUS_LOG_FLOOR)
    out[pos] = np.log10(np.maximum(values[pos], PAIRED_RADIUS_LOG_FLOOR))
    return out


